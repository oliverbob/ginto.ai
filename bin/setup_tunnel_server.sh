#!/usr/bin/env bash
# setup_tunnel_server.sh - Install and configure frps for *.silverqueen.pro tunnels
#
# Sets up the FRP server (frps) on a VPS so that gntl clients can expose local
# ports as subdomains via Caddy on-demand TLS. Runs frps as the target user
# (default: oliverbob) so the ginto.ai PHP app can read the shared token from
# /etc/frp/frps.env.
#
# Usage:
#   sudo ./bin/setup_tunnel_server.sh                     # defaults
#   sudo ./bin/setup_tunnel_server.sh --user oliverbob --domain silverqueen.pro
#   sudo ./bin/setup_tunnel_server.sh --frp-version 0.67.0 --force
#
# Can be called standalone or sourced by gintoai.sh (install_tunnel_server).

set -euo pipefail

# ---------------------------------------------------------------------------
# Configuration
# ---------------------------------------------------------------------------
FRP_VERSION="${FRP_VERSION:-0.67.0}"
FRP_ARCH="${FRP_ARCH:-linux_amd64}"
FRP_DIR="/opt/frp"
FRP_CONFIG_DIR="/etc/frp"
FRP_LOG_DIR="/var/log/frp"
FRP_WWW_DIR="/var/www/frp"

# Domain and user — overridable via flags
FRP_USER="${FRP_USER:-oliverbob}"
CADDY_DOMAIN="${CADDY_DOMAIN:-silverqueen.pro}"
CADDY_TLS_EMAIL="${CADDY_TLS_EMAIL:-admin@${CADDY_DOMAIN}}"
FORCE_INSTALL="${FORCE_INSTALL:-false}"

# ---------------------------------------------------------------------------
# Parse flags (override env defaults)
# ---------------------------------------------------------------------------
for arg in "$@"; do
    case "$arg" in
        --user=*)        FRP_USER="${arg#*=}" ;;
        --domain=*)      CADDY_DOMAIN="${arg#*=}" ;;
        --email=*)       CADDY_TLS_EMAIL="${arg#*=}" ;;
        --frp-version=*) FRP_VERSION="${arg#*=}" ;;
        --force)         FORCE_INSTALL=true ;;
        --help|-h)
            sed -n '2,/^$/{ s/^# \?//; p }' "$0"
            exit 0
            ;;
    esac
done

# ---------------------------------------------------------------------------
# Logging helpers
# ---------------------------------------------------------------------------
RED='\033[0;31m'; GREEN='\033[0;32m'; YELLOW='\033[1;33m'; BLUE='\033[0;34m'; NC='\033[0m'
log_info()    { echo -e "${BLUE}[INFO]${NC} $1"; }
log_success() { echo -e "${GREEN}[OK]${NC} $1"; }
log_warn()    { echo -e "${YELLOW}[WARN]${NC} $1"; }
log_error()   { echo -e "${RED}[ERROR]${NC} $1"; }

# ---------------------------------------------------------------------------
# Pre-flight
# ---------------------------------------------------------------------------
if [[ $EUID -ne 0 ]]; then
    log_error "This script must be run as root (use sudo)."
    exit 1
fi

if ! id "$FRP_USER" &>/dev/null; then
    log_error "User '$FRP_USER' does not exist. Create it first."
    exit 1
fi

log_info "Installing frps ${FRP_VERSION} for user ${FRP_USER} on ${CADDY_DOMAIN}"

# ---------------------------------------------------------------------------
# 1. Install frps binary
# ---------------------------------------------------------------------------
if [[ ! -f "$FRP_DIR/frps" ]] || [[ "$FORCE_INSTALL" == "true" ]]; then
    log_info "Downloading frps ${FRP_VERSION} ..."
    mkdir -p "$FRP_DIR"
    TMP="/tmp/frp_${FRP_VERSION}.tar.gz"
    curl -sSL "https://github.com/fatedier/frp/releases/download/v${FRP_VERSION}/frp_${FRP_VERSION}_${FRP_ARCH}.tar.gz" -o "$TMP"
    tar -xzf "$TMP" -C /tmp
    cp "/tmp/frp_${FRP_VERSION}_${FRP_ARCH}/frps" "$FRP_DIR/"
    cp "/tmp/frp_${FRP_VERSION}_${FRP_ARCH}/frpc" "$FRP_DIR/"
    chmod +x "$FRP_DIR/frps" "$FRP_DIR/frpc"
    rm -rf "/tmp/frp_${FRP_VERSION}_${FRP_ARCH}" "$TMP"
    ln -sf "$FRP_DIR/frps" /usr/local/bin/frps
    ln -sf "$FRP_DIR/frpc" /usr/local/bin/frpc
    log_success "frps binary installed"
else
    log_info "frps binary already present at $FRP_DIR/frps (use --force to reinstall)"
fi

# ---------------------------------------------------------------------------
# 2. Create directories
# ---------------------------------------------------------------------------
mkdir -p "$FRP_CONFIG_DIR" "$FRP_LOG_DIR" "$FRP_WWW_DIR" /etc/caddy/sites-enabled
chown -R "$FRP_USER:$FRP_USER" "$FRP_LOG_DIR" "$FRP_WWW_DIR"

# ---------------------------------------------------------------------------
# 3. Generate /etc/frp/frps.toml (only if missing or --force)
# ---------------------------------------------------------------------------
if [[ ! -f "$FRP_CONFIG_DIR/frps.toml" ]] || [[ "$FORCE_INSTALL" == "true" ]]; then
    log_info "Writing frps.toml ..."
    cat > "$FRP_CONFIG_DIR/frps.toml" << TOMLEOF
# frps configuration for ${CADDY_DOMAIN} tunnels
# Generated by setup_tunnel_server.sh

bindAddr = "0.0.0.0"
bindPort = 7000

vhostHTTPPort = 7080
vhostHTTPSPort = 7443
subDomainHost = "${CADDY_DOMAIN}"

auth.method = "token"
auth.token = "{{ .Envs.FRP_AUTH_TOKEN }}"

transport.tls.force = false
transport.maxPoolCount = 20
transport.tcpMux = true
transport.tcpMuxKeepaliveInterval = 30
transport.heartbeatTimeout = 90

allowPorts = [
    { start = 6000, end = 6999 },
    { start = 8000, end = 8999 },
    { start = 9000, end = 9999 }
]

webServer.addr = "127.0.0.1"
webServer.port = 7500
webServer.user = "admin"
webServer.password = "{{ .Envs.FRP_DASHBOARD_PWD }}"

enablePrometheus = true

log.to = "${FRP_LOG_DIR}/frps.log"
log.level = "info"
log.maxDays = 7

custom404Page = "${FRP_WWW_DIR}/404.html"
detailedErrorsToClient = true
TOMLEOF
    chown "$FRP_USER:$FRP_USER" "$FRP_CONFIG_DIR/frps.toml"
    log_success "frps.toml written"
else
    log_info "frps.toml already exists (use --force to overwrite)"
fi

# ---------------------------------------------------------------------------
# 4. Generate /etc/frp/frps.env (only if missing or --force)
# ---------------------------------------------------------------------------
if [[ ! -f "$FRP_CONFIG_DIR/frps.env" ]] || [[ "$FORCE_INSTALL" == "true" ]]; then
    log_info "Generating auth token and dashboard password ..."
    FRP_TOKEN=$(openssl rand -hex 32)
    FRP_DASH_PWD=$(openssl rand -hex 16)
    cat > "$FRP_CONFIG_DIR/frps.env" << ENVEOF
FRP_AUTH_TOKEN=${FRP_TOKEN}
FRP_DASHBOARD_PWD=${FRP_DASH_PWD}
ENVEOF
    chmod 600 "$FRP_CONFIG_DIR/frps.env"
    chown "$FRP_USER:$FRP_USER" "$FRP_CONFIG_DIR/frps.env"
    log_success "frps.env created"
else
    log_info "frps.env already exists (use --force to regenerate)"
    FRP_TOKEN=$(grep '^FRP_AUTH_TOKEN=' "$FRP_CONFIG_DIR/frps.env" | cut -d= -f2-)
    FRP_DASH_PWD=$(grep '^FRP_DASHBOARD_PWD=' "$FRP_CONFIG_DIR/frps.env" | cut -d= -f2-)
fi

# ---------------------------------------------------------------------------
# 5. Custom 404 page
# ---------------------------------------------------------------------------
if [[ ! -f "$FRP_WWW_DIR/404.html" ]] || [[ "$FORCE_INSTALL" == "true" ]]; then
    cat > "$FRP_WWW_DIR/404.html" << 'HTMLEOF'
<!DOCTYPE html>
<html><head><title>Site not live yet</title>
<style>body{font-family:sans-serif;text-align:center;padding:80px 20px;color:#555}
h1{font-size:2em;margin-bottom:.5em}p{font-size:1.2em}a{color:#667eea}</style></head>
<body><h1>This site isn't live yet</h1>
<p>No site is answering on this address right now.</p>
<p>To bring it online, sign in at <a href="https://silverqueen.pro/account/keys">silverqueen.pro/account/keys</a>,
add or copy your access key, then start your site from your device - it goes live immediately.</p>
<p>Already set up? Make sure your site has been started once on your device.</p>
</body></html>
HTMLEOF
    chown "$FRP_USER:$FRP_USER" "$FRP_WWW_DIR/404.html"
    log_success "404 page written"
fi

# ---------------------------------------------------------------------------
# 6. Systemd service — run as the target user, not root
# ---------------------------------------------------------------------------
log_info "Writing systemd service ..."
cat > /etc/systemd/system/ginto-frps.service << SVCEOF
[Unit]
Description=Ginto FRP Server (frps)
Documentation=https://github.com/fatedier/frp
After=network.target

[Service]
Type=simple
User=${FRP_USER}
Group=${FRP_USER}
WorkingDirectory=${FRP_DIR}
EnvironmentFile=${FRP_CONFIG_DIR}/frps.env
ExecStart=${FRP_DIR}/frps -c ${FRP_CONFIG_DIR}/frps.toml
ExecReload=/bin/kill -HUP \$MAINPID
Restart=always
RestartSec=5
LimitNOFILE=1048576
StandardOutput=append:${FRP_LOG_DIR}/frps.log
StandardError=append:${FRP_LOG_DIR}/frps.log

NoNewPrivileges=true
ProtectSystem=strict
ReadWritePaths=${FRP_LOG_DIR} ${FRP_DIR} ${FRP_WWW_DIR} ${FRP_CONFIG_DIR}

[Install]
WantedBy=multi-user.target
SVCEOF
log_success "ginto-frps.service written"

# ---------------------------------------------------------------------------
# 7. Caddy wildcard block — via sites-enabled so it survives Caddyfile regen
# ---------------------------------------------------------------------------
CADDY_FRP_CONF="/etc/caddy/sites-enabled/tunnels.caddy"
log_info "Writing Caddy FRP config ..."
cat > "$CADDY_FRP_CONF" << CADDYEOF
# FRP Tunnel — proxy *.${CADDY_DOMAIN} subdomains to frps HTTP vhost
*.${CADDY_DOMAIN} {
    tls {
        on_demand
    }
    reverse_proxy 127.0.0.1:7080 {
        header_up Host {host}
    }
}
CADDYEOF
log_success "Caddy config written to ${CADDY_FRP_CONF}"

# Ensure the main Caddyfile has the on_demand_tls block and sites-enabled import.
# Only patch if the file exists and is missing these.
CADDYFILE="/etc/caddy/Caddyfile"
if [[ -f "$CADDYFILE" ]]; then
    if ! grep -q 'on_demand_tls' "$CADDYFILE"; then
        log_info "Prepending on_demand_tls block to Caddyfile ..."
        TMP_CADDY=$(mktemp)
        cat > "$TMP_CADDY" << GNCEOF
{
    on_demand_tls {
        ask http://127.0.0.1:8000/api/tunnel/verify
    }
}

import sites-enabled/*

GNCEOF
        cat "$CADDYFILE" >> "$TMP_CADDY"
        cp "$TMP_CADDY" "$CADDYFILE"
        rm -f "$TMP_CADDY"
        log_success "on_demand_tls block added"
    fi
    if ! grep -q 'import sites-enabled' "$CADDYFILE"; then
        log_warn "Caddyfile is missing 'import sites-enabled/*' — add it manually."
    fi
else
    log_warn "No Caddyfile found at ${CADDYFILE} — skipping Caddy patching."
fi

# ---------------------------------------------------------------------------
# 8. Start / restart services
# ---------------------------------------------------------------------------
log_info "Reloading systemd and starting frps ..."
systemctl daemon-reload
systemctl enable ginto-frps 2>/dev/null
systemctl restart ginto-frps
sleep 2

if systemctl is-active --quiet ginto-frps; then
    log_success "frps is running as $(ps -o user= -C frps | head -1)"
else
    log_error "frps failed to start. Check: journalctl -u ginto-frps -n 20"
    exit 1
fi

# Reload Caddy if running (picks up sites-enabled/tunnels.caddy)
if systemctl is-active --quiet caddy; then
    log_info "Reloading Caddy ..."
    systemctl reload caddy
    log_success "Caddy reloaded"
fi

# ---------------------------------------------------------------------------
# 9. Verify
# ---------------------------------------------------------------------------
echo ""
echo "=============================================="
log_success "Tunnel server setup complete"
echo "=============================================="
echo ""
echo "  Binary:      ${FRP_DIR}/frps $(/opt/frp/frps --version 2>/dev/null || echo '')"
echo "  Config:      ${FRP_CONFIG_DIR}/frps.toml"
echo "  Secrets:     ${FRP_CONFIG_DIR}/frps.env"
echo "  Logs:        ${FRP_LOG_DIR}/frps.log"
echo "  404 page:    ${FRP_WWW_DIR}/404.html"
echo "  Caddy:       ${CADDY_FRP_CONF}"
echo "  Service:     ginto-frps.service (User=${FRP_USER})"
echo ""
echo "  Ports:"
echo "    7000  frpc control"
echo "    7080  HTTP vhost (Caddy proxies here)"
echo "    7443  HTTPS vhost"
echo "    7500  Dashboard (127.0.0.1)"
echo ""
echo "  FRP_AUTH_TOKEN=${FRP_TOKEN}"
echo "  FRP_DASHBOARD_PWD=${FRP_DASH_PWD}"
echo ""
echo "  Next steps:"
echo "    1. Generate a key at https://${CADDY_DOMAIN}/account/keys"
echo "    2. Use it in gntl — the bind endpoint will return these credentials"
echo "    3. Verify: curl -s -o /dev/null -w '%{http_code}' -X POST http://127.0.0.1:8000/api/tunnel/bind -H 'Content-Type: application/json' -d '{\"key\":\"test\",\"local_port\":2026}'"
echo ""
