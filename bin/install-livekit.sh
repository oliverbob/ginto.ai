#!/usr/bin/env bash
#
# LiveKit SFU on silverqueen.pro.
#
#   ssh root@162.35.101.26
#   su - oliverbob
#   cd ginto.ai && git pull
#   sudo bash bin/install-livekit.sh
#
# Idempotent: run it again after a pull and it re-writes the config, keeps the
# keys it already generated, and restarts the service. Nothing here is
# destructive except the config file, which the repository owns.
#
# WHY THE KEYS ARE NOT IN THIS REPOSITORY
#
# ginto.ai is public. An API key and secret committed here is a key anybody can
# read, and a LiveKit key is not a small thing to lose: it mints tokens, and a
# token is admission to any room on the server. So the installer generates them
# once into /etc/livekit/livekit.env, root-only, and prints them exactly once so
# they can be copied into the wallet's .env by hand. They are never echoed
# again, never committed, and never written anywhere else.

set -euo pipefail

RED='\033[0;31m'; GREEN='\033[0;32m'; YELLOW='\033[1;33m'; DIM='\033[2m'; NC='\033[0m'

say()  { echo -e "${GREEN}$*${NC}"; }
warn() { echo -e "${YELLOW}$*${NC}"; }
die()  { echo -e "${RED}$*${NC}" >&2; exit 1; }

[ "$(id -u)" -eq 0 ] || die "Run this with sudo — it writes to /etc and manages a service."

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
TMPL="$HERE/tools/livekit/livekit.yaml.tmpl"
UNIT="$HERE/tools/livekit/livekit.service"

[ -f "$TMPL" ] || die "Missing $TMPL — is this the ginto.ai checkout?"

echo "=========================================="
echo " LiveKit SFU — silverqueen.pro"
echo "=========================================="
echo

# ── 1. the binary ────────────────────────────────────────────────────────────
say "[1/7] livekit-server"

if command -v livekit-server >/dev/null 2>&1; then
    echo -e "  ${DIM}already installed: $(livekit-server --version 2>&1 | head -1)${NC}"
else
    curl -sSL https://get.livekit.io | bash >/dev/null 2>&1 \
        || die "  Could not install livekit-server."
    echo "  installed: $(livekit-server --version 2>&1 | head -1)"
fi

# ── 2. an account that owns nothing ──────────────────────────────────────────
say "[2/7] service account"

if id livekit >/dev/null 2>&1; then
    echo -e "  ${DIM}user 'livekit' exists${NC}"
else
    useradd --system --no-create-home --shell /usr/sbin/nologin livekit
    echo "  created 'livekit' (system, no shell, no home)"
fi

install -d -m 0755 -o livekit -g livekit /var/log/livekit

# root:livekit, not root:root. The config inside is 0640 root:livekit, but a
# directory the service cannot traverse makes that irrelevant — the first run
# failed with "permission denied" on a file it had every right to read.
install -d -m 0750 -o root -g livekit /etc/livekit

# ── 3. keys, generated once ──────────────────────────────────────────────────
say "[3/7] API keys"

FRESH=0

if [ -f /etc/livekit/livekit.env ]; then
    echo -e "  ${DIM}keeping the existing key in /etc/livekit/livekit.env${NC}"
else
    KEY="API$(head -c 12 /dev/urandom | base64 | tr -dc 'A-Za-z0-9' | head -c 12)"
    SECRET="$(head -c 48 /dev/urandom | base64 | tr -dc 'A-Za-z0-9' | head -c 43)"

    umask 077
    cat > /etc/livekit/livekit.env <<ENV
# Generated by bin/install-livekit.sh. Not in any repository.
# These mint room tokens: treat them as you would a signing key.
LIVEKIT_API_KEY=$KEY
LIVEKIT_API_SECRET=$SECRET
ENV
    chmod 600 /etc/livekit/livekit.env
    FRESH=1
    echo "  generated a new key pair"
fi

# shellcheck disable=SC1091
set -a; . /etc/livekit/livekit.env; set +a

[ -n "${LIVEKIT_API_KEY:-}" ] && [ -n "${LIVEKIT_API_SECRET:-}" ] \
    || die "  /etc/livekit/livekit.env is missing a key or a secret."

# ── 4. the config the repository owns ────────────────────────────────────────
say "[4/7] /etc/livekit/livekit.yaml"

# envsubst only for the two names we mean, so a ${...} anywhere else in the
# template survives untouched.
LIVEKIT_API_KEY="$LIVEKIT_API_KEY" LIVEKIT_API_SECRET="$LIVEKIT_API_SECRET" \
    envsubst '${LIVEKIT_API_KEY} ${LIVEKIT_API_SECRET}' < "$TMPL" > /etc/livekit/livekit.yaml

chmod 640 /etc/livekit/livekit.yaml
chown root:livekit /etc/livekit/livekit.yaml
echo "  written from tools/livekit/livekit.yaml.tmpl"

# ── 5. the service ───────────────────────────────────────────────────────────
say "[5/7] systemd"

install -m 0644 "$UNIT" /etc/systemd/system/livekit.service
systemctl daemon-reload
systemctl enable livekit >/dev/null 2>&1
systemctl restart livekit
sleep 2

if systemctl is-active --quiet livekit; then
    echo "  livekit.service is running"
else
    journalctl -u livekit -n 20 --no-pager || true
    die "  livekit.service did not start."
fi

# ── 6. does it actually answer ───────────────────────────────────────────────
say "[6/7] checking"

for i in $(seq 1 10); do
    if curl -fsS -m 2 http://127.0.0.1:7880/ >/dev/null 2>&1; then break; fi
    sleep 1
done

if curl -fsS -m 3 http://127.0.0.1:7880/ >/dev/null 2>&1; then
    echo "  signalling answers on 127.0.0.1:7880"
else
    warn "  127.0.0.1:7880 did not answer. Check: journalctl -u livekit -n 50"
fi

ss -lntu 2>/dev/null | grep -E ':(7880|7881|7882)\b' | sed 's/^/  /' || true

# ── 7. the public signalling socket ──────────────────────────────────────────
say "[7/7] Caddy"

CADDYFILE=/etc/caddy/Caddyfile
SNIPPET=/etc/caddy/conf.d/livekit.caddy

if [ ! -f "$CADDYFILE" ]; then
    warn "  No $CADDYFILE — skipping. Point sfu.silverqueen.pro at 127.0.0.1:7880 yourself."
else
    install -d -m 0755 /etc/caddy/conf.d

    cat > "$SNIPPET" <<'CADDY'
# LiveKit signalling. Written by ginto.ai/bin/install-livekit.sh — edit there.
#
# A named block, so it wins over the *.silverqueen.pro wildcard below it: the
# wildcard sends everything to the frp vhost, and signalling is not a tunnel.
# Caddy prefers the more specific host, so the order in the file does not
# matter, but the specificity does.
sfu.silverqueen.pro {
	# An ordinary certificate, not an on-demand one.
	#
	# This host's global block gates on-demand TLS behind
	# /api/tunnel/verify, which approves the subdomains that are registered
	# tunnels. The SFU is not a tunnel, so the ask said no and the handshake
	# failed with "tlsv1 alert internal error" and nothing in the log — a
	# refusal that looks exactly like a broken server. Naming an email here
	# issues it the ordinary way, as the apex block does.
	tls admin@silverqueen.pro

	# WebSocket upgrades need nothing special in Caddy v2 — reverse_proxy
	# carries them. The SFU binds to loopback, so this is the only way in.
	reverse_proxy 127.0.0.1:7880
}
CADDY

    if grep -q 'conf.d/\*.caddy' "$CADDYFILE"; then
        echo -e "  ${DIM}Caddyfile already imports conf.d${NC}"
    else
        cp "$CADDYFILE" "$CADDYFILE.bak.$(date +%Y%m%d%H%M%S)"
        printf '\n# Site snippets installed by scripts. See ginto.ai/bin/.\nimport /etc/caddy/conf.d/*.caddy\n' >> "$CADDYFILE"
        echo "  added an import for conf.d (previous file kept as .bak)"
    fi

    if caddy validate --config "$CADDYFILE" >/dev/null 2>&1; then
        # Validating as root leaves a root-owned file in Caddy's log directory,
        # and Caddy then refuses to start. Hand it back before reloading.
        chown -R caddy:caddy /var/log/caddy 2>/dev/null || true
        systemctl reload caddy
        echo "  sfu.silverqueen.pro -> 127.0.0.1:7880, Caddy reloaded"
    else
        caddy validate --config "$CADDYFILE" 2>&1 | tail -5 | sed 's/^/    /'
        warn "  Caddy did not validate. The snippet is written but NOT live."
    fi
fi

echo
echo "=========================================="
say " Done."
echo "=========================================="
echo
echo "Checked, and already true on this host:"
echo "  DNS       *.silverqueen.pro resolves here, so sfu.silverqueen.pro does"
echo "  Firewall  none active — udp/7882 and tcp/7881 are reachable"
echo

if [ "$FRESH" -eq 1 ]; then
    echo "------------------------------------------------------------------"
    warn " The key pair, shown once. Copy it into the wallet's .env now."
    echo "------------------------------------------------------------------"
    echo "  LIVEKIT_URL=wss://sfu.silverqueen.pro"
    echo "  LIVEKIT_API_KEY=$LIVEKIT_API_KEY"
    echo "  LIVEKIT_API_SECRET=$LIVEKIT_API_SECRET"
    echo "------------------------------------------------------------------"
    echo -e "${DIM}  It is in /etc/livekit/livekit.env and will not be printed again.${NC}"
fi
